def post(url, title, desc, og_t, kicker, h1, lead, body, about, items_ld, pola,
         faq_items=None, more=None):
    art = {"@context": "https://schema.org", "@type": "Article", "headline": og_t,
           "description": desc, "inLanguage": "he",
           "datePublished": TODAY, "dateModified": TODAY,
           "image": "https://imale.co/assets/og.jpg",
           "author": {"@type": "Person", "name": "שקמה דגרי",
                      "jobTitle": "מדריכת הורים לגיל הרך ויועצת שינה", "url": "https://imale.co"},
           "publisher": {"@type": "Person", "name": "שקמה דגרי"},
           "isPartOf": {"@type": "Blog", "name": "הבלוג של שקמה דגרי", "url": SITE + BLOG},
           "about": about, "mainEntityOfPage": SITE + url}
    ilist = {"@context": "https://schema.org", "@type": "ItemList", "name": og_t,
             "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n}
                                 for i, n in enumerate(items_ld)]}
    ld = [art, ilist, crumbs_ld(('הבלוג', SITE + BLOG), (og_t, SITE + url))]
    if faq_items:
        ld.insert(2, faq_ld(faq_items))
    html = head(title, desc, url, ld=ld, og_title=og_t, body_class='cpage')
    html += header()
    html += '<div class="wrap" id="main">\n'
    html += '  <div class="crumb"><a href="index.html">בית</a> › <a href="%s">הבלוג</a> › %s</div>\n' % (BLOG, h1)
    html += '  <div class="hero">\n' + pola
    html += '    <span class="kicker">%s</span>\n    <h1>%s</h1>\n' % (kicker, h1)
    html += ''.join('    <p class="lead">%s</p>\n' % x for x in lead)
    html += '  </div>\n'
    html += body
    html += bio_box()
    if faq_items:
        html += faq(faq_items)
    html += readmore(more or [])
    html += '</div>\n' + footer() + CLICK_JS
    write(url, html)


