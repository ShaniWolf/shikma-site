def blk(blocks):
    """בלוקים בתוך פריט: ('p', html) | ('say', label, text) | ('ul', [..])"""
    out = ''
    for b in blocks:
        if b[0] == 'p':
            out += '          <p>%s</p>\n' % b[1]
        elif b[0] == 'say':
            out += '          <p class="tl-say"><span>%s</span>״%s״</p>\n' % (b[1], b[2])
        elif b[0] == 'ul':
            out += '          <ul class="clist">%s</ul>\n' % ''.join('<li>%s</li>' % i for i in b[1])
    return out


def tl(eyeb, h2, lead, items, foot=None):
    """רשימה ממוספרת בסגנון ציר הזמן של tantrum-gil-shnatayim."""
    html = '''  <section class="tl-wrap rv">
    <p class="eyeb">%s</p>
    <h2>%s</h2>
%s    <ol class="tl">
''' % (eyeb, h2, ('    <p class="tl-lead">%s</p>\n' % lead) if lead else '')
    for i, (h, blocks) in enumerate(items, 1):
        html += '''      <li class="tl-item rv" style="--d:%ss">
        <span class="tl-n" aria-hidden="true">%d</span>
        <div class="tl-body">
          <div class="tl-top"><h3>%s</h3></div>
%s        </div>
      </li>
''' % (round((i - 1) * .05, 2), i, h, blk(blocks))
    html += '    </ol>\n'
    if foot:
        html += '    <p class="tl-foot">%s</p>\n' % foot
    html += '  </section>\n'
    return html


